def _esc(value: object) -> str:
    if value is None:
        return ""
    return html.escape(str(value))


def _truncate(text: str, limit: int) -> str:
    """Deterministic word-boundary truncation. No LLM, no randomness -- the
    same input always produces the same output."""
    text = " ".join(text.split())  # collapse whitespace/newlines
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",.;:- ")
    return f"{cut}…" if cut else f"{text[:limit].rstrip()}…"


_HEADLINE_DANGLERS = {
    "the", "a", "an", "as", "that", "which", "can", "its", "their", "with",
    "for", "and", "or", "but", "to", "of", "in", "on", "at", "by", "is",
    "are", "was", "has", "have", "framing", "called", "under", "over",
}


def _word_cap(text: str, max_words: int) -> str:
    """Deterministic word-count cap for the hero headline. Unlike _truncate
    (character-length, mid-word-safe, ellipsis-terminated), this never cuts
    mid-word and never appends an ellipsis -- the mockup's headline pattern
    is a short declarative statement, not a truncated feed line. Prefers the
    leading clause (up to the first sentence-ending punctuation) when that
    clause already fits the word budget, since that is usually the more
    complete thought."""
    text = " ".join(text.split())
    for sep in (".", ";", ":"):
        if sep in text:
            clause = text.split(sep, 1)[0].strip()
            if clause and len(clause.split()) <= max_words:
                return clause
    words = text.split()
    if len(words) <= max_words:
        return text
    kept = words[:max_words]
    # Never end a display headline on a dangling function word ("framing
    # the", "that can") -- trim trailing stopwords after the cut.
    while kept and kept[-1].lower().strip(",;:'\"") in _HEADLINE_DANGLERS:
        kept.pop()
    return " ".join(kept).rstrip(",;:")


