def _history_label(report_date: _date, today: _date) -> str:
    if report_date == today:
        return "Today"
    if report_date == today - _timedelta(days=1):
        return "Yesterday"
    age = (today - report_date).days
    if 0 < age < 7:
        return f"{age} days ago"
    return report_date.isoformat()


