def _latest_report_link(state: DashboardState) -> tuple[str, Optional[str]]:
    """(meta text, href-or-None) for the "Open full brief" deep link. There
    is no per-competitor report row in the schema (report_history is one
    archive of full-cycle briefs, not one row per barometer signal), so
    every row's "Open full brief" honestly points at the same latest report
    rather than fabricating a per-signal report id.

    The `reports.html_path` column is not populated by the production
    runner today, but the runner does publish brief.html beside the cockpit
    HTML on every run (scripts/daily_production_run.py). So: prefer a real
    html_path if one is on file, otherwise fall back to that sibling
    './brief.html' when the latest report row is dated today -- never link
    to a file that was not actually published this cycle."""
    if not state.report_history:
        return ("No brief on file yet for this cycle.", None)
    latest = state.report_history[0]
    meta = f"{latest.cadence.capitalize()} brief · {latest.report_date.isoformat()}"
    if latest.html_path:
        href = latest.html_path
    elif latest.report_date == _date.today():
        # Cache-busting fix (Arijit filed stale scores in production after a
        # fix shipped): the sibling brief.html this same run publishes must
        # not be served from a stale cache -- stamp the link with this run's
        # generated_at epoch so a re-render always produces a fresh URL.
        href = f"./brief.html?v={int(state.generated_at.timestamp())}"
    else:
        href = None
    return (meta, href)


