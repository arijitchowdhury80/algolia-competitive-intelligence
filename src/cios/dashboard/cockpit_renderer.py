@dataclass
class _CompetitorGroup:
    """One Attention Barometer row: a competitor plus its top 1-2 material
    signals this cycle. The mockup's Barometer ranks competitors, not
    individual signals -- a competitor with several material deltas in one
    cycle (e.g. 3 separate Coveo signals) must still render as one row."""

    competitor_id: int
    competitor_name: str
    attention_level: AttentionLevel
    score: float
    action_cue: str
    top_signals: list[CompetitorSignalCard]  # up to BAROMETER_PROOF_SIGNAL_LIMIT, desc by score
    row_key: object
    brief_href: Optional[str] = None


@dataclass
class _SemanticPattern:
    label: str
    description: str
    recommendation: str
    competitor_hits: dict[int, int]


def _group_cards_by_competitor(cards: list[CompetitorSignalCard]) -> list[_CompetitorGroup]:
    """Groups already materiality-ranked cards by competitor_id, preserving
    the builder's ranking: `cards` is globally sorted desc by attention_score
    (ties broken by competitor_id), so a competitor's members are already in
    desc-score order relative to each other, and the order in which distinct
    competitor_ids are first encountered while walking the list is already
    the correct row rank (a competitor's row rank is set by its single
    highest-scoring signal). This function only groups for display -- it
    does not re-rank state.competitor_cards."""
    order: list[int] = []
    members: dict[int, list[CompetitorSignalCard]] = {}
    for card in cards:
        if card.competitor_id not in members:
            members[card.competitor_id] = []
            order.append(card.competitor_id)
        members[card.competitor_id].append(card)

    groups: list[_CompetitorGroup] = []
    for competitor_id in order:
        group_members = members[competitor_id]
        top = group_members[0]  # highest-scoring signal for this competitor
        groups.append(
            _CompetitorGroup(
                competitor_id=competitor_id,
                competitor_name=top.competitor_name,
                attention_level=top.attention_level,
                score=top.attention_score,
                action_cue=top.action_cue or "No action cue on file.",
                top_signals=group_members[:BAROMETER_PROOF_SIGNAL_LIMIT],
                row_key=top.delta_id if top.delta_id is not None else competitor_id,
                brief_href=top.brief_href,
            )
        )
    return groups


def _render_barometer_row(state: DashboardState, group: _CompetitorGroup, *, is_first: bool) -> str:
    row_class, bar_color, bar_label = _ATTENTION_ROW[group.attention_level]
    row_id = f"competitor-{group.competitor_id}-{group.row_key}"
    open_attr = " open" if is_first else ""
    cue_full = group.action_cue
    cue_short = _esc(_truncate(cue_full, CUE_TRUNCATE_LEN))
    score = max(0.0, min(100.0, group.score))
    meta, href = _latest_report_link(state)
    if group.brief_href:
        href = group.brief_href
    if href:
        deep_link = f'<a class="deep-link" href="{_esc(href)}">Open full brief</a>'
    else:
        deep_link = '<span class="deep-link" aria-disabled="true">No brief on file</span>'

    proof_blocks = []
    bib_items: list[str] = []
    seen_evidence_urls: set = set()
    for signal in group.top_signals:
        signal_cue = signal.action_cue or cue_full
        proof_body = signal.why_it_matters or signal.what_changed or signal_cue
        proof_heading = _esc(_truncate(signal_cue, PROOF_HEADING_TRUNCATE_LEN))
        proof_blocks.append(f"<h3>{proof_heading}</h3>\n      <p>{_esc(proof_body)}</p>")
        for eid in signal.evidence_ids or []:
            # Dedupe per accordion, first occurrence wins: the same URL can
            # legitimately be cited by more than one signal in this
            # competitor's group (BAROMETER_PROOF_SIGNAL_LIMIT signals share
            # the same bibliography), and must appear once, not once per
            # citing signal.
            if eid in seen_evidence_urls:
                continue
            seen_evidence_urls.add(eid)
            bib_items.append(
                f"<li><strong>evidence</strong><a href=\"{_esc(eid)}\">{_esc(eid)}</a><em>cited</em></li>"
            )
    proof_html = "\n      ".join(proof_blocks)
    bib_html = (
        "".join(bib_items)
        if bib_items
        else "<li><strong>evidence</strong><span>No evidence link on file for this signal.</span></li>"
    )
    aria_label = _esc(
        f"{group.competitor_name}, {bar_label.lower()}, score {score:g}. {cue_full}."
    )
    return f"""<details class="attention-row {row_class}" id="{row_id}" data-competitor-id="{_esc(group.competitor_id)}" data-competitor-name="{_esc(group.competitor_name)}"{open_attr}>
  <summary class="attention-summary" aria-label="{aria_label}">
    <div class="competitor-label">
      <span class="competitor-name">{_esc(group.competitor_name)}</span>
      <span class="attention-cue">{cue_short}</span>
    </div>
    <div class="attention-track"><div class="attention-bar {bar_color}" style="width:{score:g}%">{bar_label}</div></div>
    <div class="attention-score">{score:g}</div>
  </summary>
  <div class="attention-proof">
    <div class="attention-proof-inner">
      <span>{_esc(group.competitor_name)} / {bar_label.lower()}</span>
      {proof_html}
      <div class="proof-actions">
        <div class="proof-meta">{_esc(meta)}</div>
        {deep_link}
      </div>
      <details class="inline-brief" id="report-{row_id}">
        <summary class="deep-link">Sources</summary>
        <div class="brief-article">
          <div class="report-card">
            <h3>Sources and bibliography</h3>
            <ul class="bibliography" aria-label="Evidence trail for {_esc(group.competitor_name)}">
              {bib_html}
            </ul>
          </div>
        </div>
      </details>
    </div>
  </div>
</details>"""


def _render_barometer(state: DashboardState) -> str:
    if not state.competitor_cards:
        return '<p class="caption">No competitor attention signals this cycle -- nothing rose above the reporting threshold.</p>'
    groups = _group_cards_by_competitor(state.competitor_cards)
    rows = [
        _render_barometer_row(state, group, is_first=(i == 0))
        for i, group in enumerate(groups)
    ]
    return f'<div class="attention-board" aria-label="Competitor Attention Barometer ranking competitors by attention needed this week">\n{"".join(rows)}\n</div>'


def _format_dt(value) -> str:
    if value is None:
        return "not checked yet"
    if hasattr(value, "strftime"):
        return value.strftime("%Y-%m-%d %H:%M UTC")
    return str(value)


